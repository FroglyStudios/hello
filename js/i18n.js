document.addEventListener('DOMContentLoaded', () => {
    const langToggleBtn = document.getElementById('lang-toggle');
    const langIcon = document.getElementById('lang-icon');
    
    // Default language is English, or what was saved
    let currentLang = localStorage.getItem('frogly_lang') || 'en';
    
    function applyTranslations(lang) {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            // If the element has innerHTML in the translation, use innerHTML, else textContent
            // (We have some <strong> tags in 'about.p2')
            if (translations[lang][key]) {
                if (translations[lang][key].includes('<')) {
                    el.innerHTML = translations[lang][key];
                } else {
                    el.textContent = translations[lang][key];
                }
            }
        });
        
        // Update html lang attribute
        document.documentElement.lang = lang;
        
        // Update language label next to icon (if we had one, but user wants icon only)
    }
    
    // Initial apply
    applyTranslations(currentLang);
    
    // Setup Toggle Button
    if (langToggleBtn) {
        langToggleBtn.addEventListener('click', (e) => {
            e.preventDefault();
            currentLang = currentLang === 'en' ? 'de' : 'en';
            localStorage.setItem('frogly_lang', currentLang);
            applyTranslations(currentLang);
        });
    }
});
